import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root=new URL('../',import.meta.url);
const context={window:{},document:{getElementById:()=>null}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(new URL('web/src/data.js',root),'utf8'),context);
const app=fs.readFileSync(new URL('web/src/app.js',root),'utf8');
vm.runInContext(app.slice(0,app.indexOf('function barChart')),context);
const all=vm.runInContext('summarize(D.rows)',context);
assert.equal(all.count,38375);
assert.equal(all.total,3293580300);
assert.equal(all.patients,2970);
const clinic=vm.runInContext("summarize(D.rows.filter(r=>r[0].startsWith('2025')&&r[2]==='31'))",context);
assert.equal(clinic.count,15374);
assert.equal(clinic.total,544714500);
assert.equal(clinic.patients,2705);
assert.equal(Object.keys(all.months).length,24);
console.log('PASS: actual app aggregation, full totals, year/type filter, 24 months.');
